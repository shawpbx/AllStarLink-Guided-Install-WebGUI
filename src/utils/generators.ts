export function generateInstallScript(config: NodeConfiguration): string {
  const { platform, allstar, dvswitch, security } = config;
  const platformMeta = PLATFORM_OPTIONS.find((p) => p.id === platform.target);
  const callsign = allstar.callsign.trim().toUpperCase();
  const node = allstar.nodeNumber.trim();

  const rptConf = generateRptConf(config);
  const iaxConf = generateIaxConf(config);
  const extensionsConf = generateExtensionsConf(config);
  const simpleUsbConf = generateSimpleUsbConf(config);
  const managerConf = generateManagerConf(config);
  const mmdvmIni = generateMmdvmBridgeIni(config);
  const analogIni = generateAnalogBridgeIni(config);
  const dvSwitchIni = generateDvSwitchIni(config);
  const dashboardHtml = generateStandaloneDashboardHtml(config);

  const isRpi = platform.target.startsWith('rpi');
  const isTrixie = platformMeta?.codename === 'trixie';
  const sq = (val: string) => `'${val.replace(/'/g, `'"'"'`)}'`;
  const targetUser = (platform.adminUsername.trim() || 'pi').replace(/[^a-z0-9_-]/gi, '');
  const wifiSsid = platform.wifiSsid.trim();
  const wifiPass = platform.wifiPassword;
  const wifiCountry = (platform.wifiCountry || 'US').toUpperCase();

  return `#!/usr/bin/env bash
# ============================================================================
# AllStarLink 3 (ASL3)${dvswitch.enabled ? ' + DVSwitch Server' : ''} Automated Node Installer
# Target: ${platformMeta?.label || platform.target}
# Node: ${node} (${callsign})
# Generated by AllStarLink Guided Install WebGUI
# ============================================================================

set -euo pipefail

if [[ "\${EUID}" -ne 0 ]]; then
  echo "[ERROR] Please run this installer as root: sudo bash $0"
  exit 1
fi

LOG_FILE="/var/log/asl-dvswitch-install.log"
exec > >(tee -a "\${LOG_FILE}") 2>&1

echo "========================================================================"
echo " Starting AllStarLink 3${dvswitch.enabled ? ' + DVSwitch' : ''} Installation"
echo " Node: ${node} | Callsign: ${callsign} | Hostname: ${platform.hostname}"
echo "========================================================================"

# ----------------------------------------------------------------------------
# 1. System Preparation, User Account, Wi-Fi, Hostname & Prerequisites
# ----------------------------------------------------------------------------
export DEBIAN_FRONTEND=noninteractive

hostnamectl set-hostname "${platform.hostname.trim()}" || true
timedatectl set-timezone "${platform.timezone}" || true

apt-get update -y
apt-get install -y --no-install-recommends \\
  curl wget gnupg2 ca-certificates lsb-release apt-transport-https \\
  software-properties-common build-essential dkms bc jq sqlite3 \\
  python3 python3-pip net-tools dnsutils usbutils alsa-utils sudo

${platform.createCustomUser ? `# Configure non-root sudo user (${targetUser}) with audio & serial device access
TARGET_USER=${sq(targetUser)}
if ! id -u "\${TARGET_USER}" >/dev/null 2>&1; then
  echo "[INFO] Creating user \${TARGET_USER}..."
  useradd -m -s /bin/bash "\${TARGET_USER}"
fi
usermod -aG sudo,audio,dialout,plugdev "\${TARGET_USER}" || true
${platform.adminPassword ? `printf '%s:%s\\n' "\${TARGET_USER}" ${sq(platform.adminPassword)} | chpasswd
echo "[INFO] Updated password for user \${TARGET_USER}."` : `# Password left unchanged for \${TARGET_USER}`}
${platform.sshAuthorizedKey.trim() ? `USER_HOME="$(getent passwd "\${TARGET_USER}" | cut -d: -f6)"
mkdir -p "\${USER_HOME}/.ssh"
AUTH_KEY=${sq(platform.sshAuthorizedKey.trim())}
grep -qxF "\${AUTH_KEY}" "\${USER_HOME}/.ssh/authorized_keys" 2>/dev/null || echo "\${AUTH_KEY}" >> "\${USER_HOME}/.ssh/authorized_keys"
chmod 700 "\${USER_HOME}/.ssh"
chmod 600 "\${USER_HOME}/.ssh/authorized_keys"
chown -R "\${TARGET_USER}:\${TARGET_USER}" "\${USER_HOME}/.ssh"
echo "[INFO] Added SSH authorized key for \${TARGET_USER}."` : '# No SSH authorized key supplied'}` : '# Custom admin user creation skipped per configuration'}

${platform.configureWifi && wifiSsid ? `# Configure Raspberry Pi / Wireless Regulatory Domain & Wi-Fi Network
echo "[INFO] Configuring Wi-Fi (${wifiCountry}) for SSID ${wifiSsid}..."
apt-get install -y --no-install-recommends rfkill iw || true
rfkill unblock wifi || true
if command -v raspi-config >/dev/null 2>&1; then
  raspi-config nonint do_wifi_country ${sq(wifiCountry)} || true
fi
iw reg set ${sq(wifiCountry)} || true

WIFI_SSID=${sq(wifiSsid)}
WIFI_PSK=${sq(wifiPass)}
if command -v nmcli >/dev/null 2>&1 && systemctl is-active --quiet NetworkManager; then
  nmcli connection delete "\${WIFI_SSID}" >/dev/null 2>&1 || true
  if [[ -n "\${WIFI_PSK}" ]]; then
    nmcli connection add type wifi ifname '*' con-name "\${WIFI_SSID}" ssid "\${WIFI_SSID}" \\
      802-11-wireless.hidden ${platform.wifiHidden ? 'yes' : 'no'} \\
      wifi-sec.key-mgmt wpa-psk wifi-sec.psk "\${WIFI_PSK}" \\
      connection.autoconnect yes
  else
    nmcli connection add type wifi ifname '*' con-name "\${WIFI_SSID}" ssid "\${WIFI_SSID}" \\
      802-11-wireless.hidden ${platform.wifiHidden ? 'yes' : 'no'} \\
      connection.autoconnect yes
  fi
  nmcli connection up "\${WIFI_SSID}" || echo "[WARN] Wi-Fi profile saved; interface will connect when in range."
else
  apt-get install -y --no-install-recommends wpasupplicant || true
  mkdir -p /etc/wpa_supplicant
  cat <<EOF_WPA > /etc/wpa_supplicant/wpa_supplicant.conf
ctrl_interface=DIR=/var/run/wpa_supplicant GROUP=netdev
update_config=1
country=${wifiCountry}

network={
    ssid="${wifiSsid.replace(/"/g, '\\"')}"
${platform.wifiHidden ? '    scan_ssid=1\n' : ''}${wifiPass ? `    psk="${wifiPass.replace(/"/g, '\\"')}"` : '    key_mgmt=NONE'}
}
EOF_WPA
  chmod 600 /etc/wpa_supplicant/wpa_supplicant.conf
  systemctl restart wpa_supplicant || true
fi` : '# Wi-Fi configuration skipped per configuration'}

# Install matching kernel headers for DAHDI (required by AllStarLink app_rpt)
KERNEL_REL="$(uname -r)"
echo "[INFO] Detected kernel: \${KERNEL_REL}"
if apt-cache show "linux-headers-\${KERNEL_REL}" >/dev/null 2>&1; then
  apt-get install -y "linux-headers-\${KERNEL_REL}"
${isRpi ? `elif apt-cache show raspberrypi-kernel-headers >/dev/null 2>&1; then
  apt-get install -y raspberrypi-kernel-headers` : `elif apt-cache show linux-headers-amd64 >/dev/null 2>&1; then
  apt-get install -y linux-headers-amd64`}
else
  echo "[WARN] Exact kernel headers package not found in cache; continuing with DAHDI install."
fi

${platform.enableZramSwap ? `# Enable zram-tools swap optimization for Raspberry Pi SD card longevity
if apt-cache show zram-tools >/dev/null 2>&1; then
  apt-get install -y zram-tools
  systemctl enable --now zramswap.service || true
fi` : '# zram-tools skipped per configuration'}

# ----------------------------------------------------------------------------
# 2. Download & Install AllStarLink 3 (ASL3)
# ----------------------------------------------------------------------------
echo "[INFO] Configuring official AllStarLink 3 APT repository..."
CODENAME="$(. /etc/os-release && echo "\${VERSION_CODENAME:-bookworm}")"
echo "[INFO] Detected OS codename: \${CODENAME}"

curl -fsSL "https://repo.allstarlink.org/public/asl-apt-repos.deb" -o /tmp/asl-apt-repos.deb
dpkg -i /tmp/asl-apt-repos.deb || apt-get -f install -y
rm -f /tmp/asl-apt-repos.deb

${isTrixie ? `# Debian 13 (Trixie) repository suite fallback check
if ! apt-get update -y; then
  echo "[WARN] AllStarLink repo did not publish '\${CODENAME}' suite yet; pinning bookworm suite compatibility..."
  find /etc/apt/sources.list.d/ -name "*allstar*" -exec sed -i "s/\${CODENAME}/bookworm/g" {} +
  apt-get update -y
fi` : 'apt-get update -y'}

echo "[INFO] Installing ASL3 core packages (asl3, asl3-asterisk, asl3-menu, dahdi)..."
apt-get install -y asl3 asl3-asterisk asl3-menu

${platform.installAllmon3 ? `echo "[INFO] Installing Allmon3 Web Monitor..."
apt-get install -y allmon3 || echo "[WARN] allmon3 package unavailable in current suite."` : '# Allmon3 skipped per configuration'}

${platform.installCockpit ? `echo "[INFO] Installing Cockpit Web Console..."
apt-get install -y cockpit
systemctl enable --now cockpit.socket || true` : '# Cockpit skipped per configuration'}

# ----------------------------------------------------------------------------
# 3. Backup Existing Asterisk Configs & Write Node ${node} Configuration
# ----------------------------------------------------------------------------
${security.backupExistingConfigs ? `BACKUP_DIR="/etc/asterisk/backup.$(date +%Y%m%d-%H%M%S)"
if [[ -d /etc/asterisk ]]; then
  mkdir -p "\${BACKUP_DIR}"
  cp -a /etc/asterisk/*.conf "\${BACKUP_DIR}/" 2>/dev/null || true
  echo "[INFO] Backed up existing Asterisk configs to \${BACKUP_DIR}"
fi` : '# Existing config backup skipped'}

cat <<'EOF_RPT' > /etc/asterisk/rpt.conf
${rptConf}
EOF_RPT

cat <<'EOF_IAX' > /etc/asterisk/iax.conf
${iaxConf}
EOF_IAX

cat <<'EOF_EXT' > /etc/asterisk/extensions.conf
${extensionsConf}
EOF_EXT

cat <<'EOF_USB' > /etc/asterisk/simpleusb.conf
${simpleUsbConf}
EOF_USB

cat <<'EOF_MGR' > /etc/asterisk/manager.conf
${managerConf}
EOF_MGR

# Ensure chan_usrp and chan_simpleusb are loaded in modules.conf if present
if [[ -f /etc/asterisk/modules.conf ]]; then
  ${dvswitch.enabled ? `grep -q "chan_usrp.so" /etc/asterisk/modules.conf || echo "load = chan_usrp.so" >> /etc/asterisk/modules.conf` : '# chan_usrp not required when DVSwitch is disabled'}
  ${allstar.radioInterface === 'simpleusb' ? `grep -q "chan_simpleusb.so" /etc/asterisk/modules.conf || echo "load = chan_simpleusb.so" >> /etc/asterisk/modules.conf` : ''}
fi

chown -R asterisk:asterisk /etc/asterisk || true
chmod 640 /etc/asterisk/iax.conf /etc/asterisk/manager.conf || true

${dvswitch.enabled ? `# ----------------------------------------------------------------------------
# 4. Download & Install DVSwitch Server + Bridge Configuration
# ----------------------------------------------------------------------------
echo "[INFO] Adding DVSwitch APT repository..."
ARCH="$(dpkg --print-architecture)"
if [[ "\${ARCH}" == "amd64" ]] && ! dpkg --print-foreign-architectures | grep -q "i386"; then
  dpkg --add-architecture i386 || true
fi
if [[ "\${ARCH}" == "arm64" ]] && ! dpkg --print-foreign-architectures | grep -q "armhf"; then
  dpkg --add-architecture armhf || true
fi

wget -q http://dvswitch.org/buster -O /tmp/dvswitch-repo || wget -q http://dvswitch.org/bullseye -O /tmp/dvswitch-repo
chmod +x /tmp/dvswitch-repo
/tmp/dvswitch-repo || true
rm -f /tmp/dvswitch-repo

# Ensure DVSwitch repo uses stable Debian suite on Debian 13 (Trixie)
if [[ -f /etc/apt/sources.list.d/dvswitch.list ]]; then
  sed -i 's/trixie/bookworm/g' /etc/apt/sources.list.d/dvswitch.list || true
fi

apt-get update -y
apt-get install -y dvswitch-server || {
  echo "[WARN] dvswitch-server metapackage fallback; installing individual bridge components..."
  apt-get install -y mmdvm-bridge analog-bridge md380-emu dvswitch-base || true
}

mkdir -p /opt/MMDVM_Bridge /opt/Analog_Bridge /var/lib/dvswitch /var/log/mmdvm

cat <<'EOF_DVS_INI' > /opt/MMDVM_Bridge/DVSwitch.ini
${dvSwitchIni}
EOF_DVS_INI

cat <<'EOF_AB_INI' > /opt/Analog_Bridge/Analog_Bridge.ini
${analogIni}
EOF_AB_INI

cat <<'EOF_MB_INI' > /opt/MMDVM_Bridge/MMDVM_Bridge.ini
${mmdvmIni}
EOF_MB_INI

# Download latest DMR subscriber ID database for metadata display
if [[ -x /opt/MMDVM_Bridge/dvswitch.sh ]]; then
  /opt/MMDVM_Bridge/dvswitch.sh update || true
fi

systemctl enable --now md380-emu.service || true
systemctl enable --now analog_bridge.service || true
systemctl enable --now mmdvm_bridge.service || true
systemctl restart md380-emu.service analog_bridge.service mmdvm_bridge.service || true` : `# ----------------------------------------------------------------------------
# 4. DVSwitch Installation Skipped (Disabled in Wizard)
# ----------------------------------------------------------------------------
echo "[INFO] DVSwitch installation skipped per configuration."`}

${platform.installLocalDashboard ? `# ----------------------------------------------------------------------------
# 5. Deploy Local HTML Configuration Dashboard Wizard on Node
# ----------------------------------------------------------------------------
mkdir -p /opt/asl-dashboard
cat <<'EOF_HTML' > /opt/asl-dashboard/index.html
${dashboardHtml}
EOF_HTML

cat <<'EOF_SVC' > /etc/systemd/system/asl-dashboard.service
[Unit]
Description=AllStarLink HTML Configuration Dashboard Wizard
After=network-online.target asterisk.service
Wants=network-online.target

[Service]
Type=simple
User=root
WorkingDirectory=/opt/asl-dashboard
ExecStart=/usr/bin/python3 -m http.server ${platform.dashboardPort} --bind ${platform.dashboardBindAll ? '0.0.0.0' : '127.0.0.1'}
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF_SVC

systemctl daemon-reload
systemctl enable --now asl-dashboard.service` : '# 5. Local HTML Dashboard service skipped per configuration'}

# ----------------------------------------------------------------------------
# 6. Firewall (UFW), Security & Service Startup
# ----------------------------------------------------------------------------
${security.enableUfw ? `apt-get install -y ufw
ufw default deny incoming
ufw default allow outgoing
ufw allow ${platform.sshPort}/tcp comment 'SSH'
ufw allow ${allstar.iaxPort}/udp comment 'AllStarLink IAX2'
${platform.installAllmon3 ? `ufw allow 80/tcp comment 'Allmon3 HTTP'\nufw allow 443/tcp comment 'Allmon3 HTTPS'` : ''}
${platform.installCockpit ? `ufw allow 9090/tcp comment 'Cockpit Console'` : ''}
${platform.installLocalDashboard && security.allowExternalDashboard ? `ufw allow ${platform.dashboardPort}/tcp comment 'ASL HTML Dashboard'` : ''}
${dvswitch.enabled ? `ufw allow ${dvswitch.dmrMasterPort}/udp comment 'DVSwitch DMR Master'` : ''}
ufw --force enable` : '# UFW firewall skipped per configuration'}

${security.enableFail2Ban ? `apt-get install -y fail2ban
systemctl enable --now fail2ban || true` : '# Fail2Ban skipped per configuration'}

${security.unattendedUpgrades ? `apt-get install -y unattended-upgrades
dpkg-reconfigure -f noninteractive unattended-upgrades || true` : '# Unattended upgrades skipped per configuration'}

systemctl enable --now asterisk.service
systemctl restart asterisk.service

# ----------------------------------------------------------------------------
# 7. Post-Install Verification Summary
# ----------------------------------------------------------------------------
sleep 3
echo ""
echo "========================================================================"
echo " Installation Complete — Node ${node} (${callsign})"
echo "========================================================================"
asterisk -rx "rpt nodes ${node}" || true
${dvswitch.enabled ? 'systemctl --no-pager status mmdvm_bridge analog_bridge md380-emu | head -n 20 || true' : ''}
${platform.installLocalDashboard ? `NODE_IP="$(hostname -I | awk '{print $1}')"
echo " Local HTML Configuration Dashboard: http://\${NODE_IP}:${platform.dashboardPort}"` : ''}
echo " Install log saved to: \${LOG_FILE}"
echo "========================================================================"
`;
}

